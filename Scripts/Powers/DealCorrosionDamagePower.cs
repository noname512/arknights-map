namespace ArknightsMap.Scripts.Powers;

[RegisterPower]
public class DealCorrosionDamagePower : ModPowerTemplate
{
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Single;

    protected override IEnumerable<DynamicVar> CanonicalVars => [];

    public override int DisplayAmount => (int)DynamicVars["Time"].BaseValue;

    protected override IEnumerable<IHoverTip> AdditionalHoverTips => [HoverTipFactory.FromPower<CorrosionDamagePower>()];

    public override PowerAssetProfile AssetProfile =>
        new(IconPath: $"res://ArknightsMap/images/powers/{GetType().Name}.png", BigIconPath: $"res://ArknightsMap/images/powers/{GetType().Name}.png");

    public override async Task AfterDamageReceived(
        PlayerChoiceContext choiceContext,
        Creature target,
        DamageResult result,
        ValueProp props,
        Creature? dealer,
        CardModel? cardSource
    )
    {
        if (dealer == Owner && target.Monster is not Osty)
        {
            await PowerCmd.Apply<CorrosionDamagePower>(new ThrowingPlayerChoiceContext(), target, 1m, Owner, null);
        }
    }
}
